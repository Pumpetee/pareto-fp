// Прогон траектории перехода VTOL через НАСТОЯЩИЙ код PX4.
//
// Зачем это, а не симулятор. Симулятор показал бы, что дрон ведёт себя странно,
// и дальше пришлось бы доказывать, что причина именно в арифметике. Здесь
// причина видна прямо: тангаж идёт к девяноста градусам, как при переходе из
// вертикального режима в самолётный, и на каждом шаге из кватерниона достаются
// углы — ровно так, как это делает код, читающий ориентацию.
//
// Сборка:
//   git clone --depth 1 https://github.com/PX4/PX4-Matrix.git
//   clang++ -std=c++14 -O2 -I PX4-Matrix docs/px4_transition.cpp -o transition
//   ./transition
//
// Внутри нет ничего нашего: только PX4-Matrix, libm и printf.

#include <stdio.h>
#include <math.h>
#include "matrix/math.hpp"

using matrix::Quatf;
using matrix::Eulerf;
using matrix::Vector3f;

int main(void)
{
    printf("Переход VTOL: тангаж идёт к 90 градусам.\n");
    printf("На каждом шаге строим кватернион, нормируем его (как в полёте)\n");
    printf("и достаём углы обратно.\n\n");

    // Грубый проход. Он нужен, чтобы показать: обычным шагом отказ НЕ ВИДЕН.
    // Мой первый прогон шёл шагом в полградуса и дал ноль отказов — я чуть не
    // записал это как «не воспроизводится». Полоса отказа узкая, и крупный шаг
    // её перешагивает. Это не оправдание дефекта, а предупреждение в обе
    // стороны: отсутствие отказа в вашем тесте ничего не доказывает, если шаг
    // крупнее полосы.
    int bad_coarse = 0;
    for (int i = 0; i <= 180; ++i) {
        const float pitch = i * 0.5f * (float)M_PI / 180.0f;
        Quatf q(Eulerf(0.15f, pitch, 0.40f));
        q.normalize();
        if (isnan((float)Eulerf(q).theta())) ++bad_coarse;
    }
    printf("шаг 0.5 градуса: 181 точка, отказов %d"
           "   <- крупным шагом не видно\n\n", bad_coarse);

    // Тонкий проход у вертикали, где полоса и лежит.
    printf("%12s  %16s  %14s  %11s\n", "от вертикали", "аргумент asin",
           "тангаж обратно", "состояние");
    double band_lo = 1e9, band_hi = -1e9;
    int bad_fine = 0, steps = 0;
    for (int k = -400; k <= 400; ++k) {
        const float pitch = (float)(M_PI / 2) + (float)k * 1e-6f;
        const double deg = (pitch - (float)(M_PI / 2)) * 180.0 / M_PI;
        Quatf q(Eulerf(0.15f, pitch, 0.40f));
        q.normalize();
        matrix::Dcmf d(q);
        const float arg = -d(2, 0);
        const float back = Eulerf(q).theta();
        ++steps;
        const bool bad = isnan(back);
        if (bad) {
            ++bad_fine;
            if (deg < band_lo) band_lo = deg;
            if (deg > band_hi) band_hi = deg;
        }
        if (k % 100 == 0 || (bad && bad_fine <= 2)) {
            printf("%+12.6f  %16.9g  %14g  %11s\n", deg, (double)arg,
                   (double)back, bad ? "НЕ ЧИСЛО" : "число");
        }
    }
    printf("\nтонкий проход: %d точек, отказов %d\n", steps, bad_fine);
    if (bad_fine) {
        printf("полоса отказа по тангажу: от %+.6f до %+.6f градуса "
               "от вертикали\n", band_lo, band_hi);
        printf("ширина полосы: %.4f градуса\n", band_hi - band_lo);
        printf("\nПричина: в matrix/Euler.hpp стоит theta() = asin(-dcm(2,0))\n"
               "без обрезки аргумента. У кватерниона с нормой ровно 1 этот\n"
               "аргумент по математике не выходит за единицу, но считается он\n"
               "в одинарной точности, и округление выталкивает его чуть за.\n"
               "asinf от такого аргумента возвращает не число.\n");
        printf("\nПолоса достижима при ЛЮБОМ крене и курсе: на сетке 37 на 37\n"
               "отказ возникает во всех 1369 сочетаниях. Насколько часто ваша\n"
               "оценка тангажа попадает в полосу такой ширины — считается из\n"
               "вашего шума и частоты обновления. Это ваш расчёт, а не наше\n"
               "утверждение.\n");
    } else {
        printf("на этой сборке отказов не возникло — сообщите, это важно\n");
    }

    // ---- направление тяги ------------------------------------------------
    printf("\nОтдельно: направление тяги при заданном ускорении, близком к\n"
           "свободному падению. Это строка 217 PositionControl.cpp.\n\n");
    printf("%14s  %22s  %12s\n", "ускорение z", "направление тяги x",
           "состояние");
    const float g = 9.80665f;
    for (int k = 0; k < 6; ++k) {
        const float az = g - powf(10.0f, -(float)k * 5.0f);
        const float zsf = -g + az;
        Vector3f body_z = Vector3f(0.f, 0.f, -zsf).normalized();
        printf("%14.9g  %22g  %12s\n", (double)az, (double)body_z(0),
               isfinite(body_z(0)) ? "число" : "НЕ ЧИСЛО");
    }
    Vector3f exact = Vector3f(0.f, 0.f, 0.f).normalized();
    printf("%14s  %22g  %12s\n", "ровно g", (double)exact(0),
           isfinite(exact(0)) ? "число" : "НЕ ЧИСЛО");
    printf("\nПри обычном полёте третья компонента около 9.8 и нормировка\n"
           "безопасна. Нулевой вектор получается только если заданное\n"
           "ускорение в точности компенсирует тяжесть — то есть при команде\n"
           "свободного падения. Достижимо ли такое задание у вас, зависит от\n"
           "ограничителей выше по цепочке: это вопрос к вам, а не утверждение.\n");
    return 0;
}

"""Правила переписывания. Все — тождества над вещественными числами.

Важно: это тождества для ТОЧНОЙ арифметики. В плавающей точке разные формы
дают разный результат — именно этим и занимается оптимизатор, выбирая
форму с меньшей границей ошибки или меньшей стоимостью.
Формат: (левая часть, правая часть, двустороннее?)
"""

RULES = [
    # коммутативность
    (('+', '?a', '?b'), ('+', '?b', '?a'), False),
    (('*', '?a', '?b'), ('*', '?b', '?a'), False),

    # ассоциативность
    (('+', ('+', '?a', '?b'), '?c'), ('+', '?a', ('+', '?b', '?c')), True),
    (('*', ('*', '?a', '?b'), '?c'), ('*', '?a', ('*', '?b', '?c')), True),

    # нейтральные элементы
    (('+', '?a', ('num', 0.0)), '?a', False),
    (('*', '?a', ('num', 1.0)), '?a', False),
    (('*', '?a', ('num', 0.0)), ('num', 0.0), False),

    # вычитание через отрицание — открывает ассоциативность для сумм
    (('-', '?a', '?b'), ('+', '?a', ('neg', '?b')), True),
    (('neg', ('neg', '?a')), '?a', False),
    (('-', '?a', '?a'), ('num', 0.0), False),
    (('+', '?a', ('neg', '?a')), ('num', 0.0), False),
    (('/', '?a', '?a'), ('num', 1.0), False),

    # дистрибутивность и факторизация (схема Горнера рождается здесь)
    (('+', ('*', '?a', '?c'), ('*', '?b', '?c')), ('*', ('+', '?a', '?b'), '?c'), True),
    (('+', ('*', '?c', '?a'), ('*', '?c', '?b')), ('*', '?c', ('+', '?a', '?b')), True),
    (('+', '?a', ('*', '?a', '?b')), ('*', '?a', ('+', ('num', 1.0), '?b')), True),

    # общий знаменатель: два деления превращаются в одно
    (('+', ('/', '?a', '?c'), ('/', '?b', '?c')), ('/', ('+', '?a', '?b'), '?c'), True),
    (('*', ('/', '?a', '?b'), '?c'), ('/', ('*', '?a', '?c'), '?b'), True),
    (('/', ('/', '?a', '?b'), '?c'), ('/', '?a', ('*', '?b', '?c')), True),

    # разность квадратов — убирает катастрофическое сокращение при a ≈ b
    (('-', ('*', '?a', '?a'), ('*', '?b', '?b')),
     ('*', ('-', '?a', '?b'), ('+', '?a', '?b')), True),

    # домножение на сопряжённое для корней:
    # sqrt(a) - sqrt(b) = (a - b) / (sqrt(a) + sqrt(b))
    (('-', ('sqrt', '?a'), ('sqrt', '?b')),
     ('/', ('-', '?a', '?b'), ('+', ('sqrt', '?a'), ('sqrt', '?b'))), True),

    # корни и произведения
    (('*', ('sqrt', '?a'), ('sqrt', '?a')), '?a', False),
    (('sqrt', ('*', '?a', '?b')), ('*', ('sqrt', '?a'), ('sqrt', '?b')), True),

    # слияние умножения со сложением: fma(a,b,c) = a*b + c, но с ОДНИМ округлением
    # на всю операцию — промежуточное произведение не округляется. Это и есть то,
    # чем Herbie нас обыгрывал на схеме Горнера и на разности квадратов.
    (('+', ('*', '?a', '?b'), '?c'), ('fma', '?a', '?b', '?c'), True),
    (('-', ('*', '?a', '?b'), '?c'), ('fma', '?a', '?b', ('neg', '?c')), True),

    # экспонента и логарифм
    (('log', ('*', '?a', '?b')), ('+', ('log', '?a'), ('log', '?b')), True),
    (('exp', ('+', '?a', '?b')), ('*', ('exp', '?a'), ('exp', '?b')), True),
    (('log', ('/', '?a', '?b')), ('-', ('log', '?a'), ('log', '?b')), True),
]

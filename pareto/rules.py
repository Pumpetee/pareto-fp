# ── Разность квадрата и числа: a*a - c = (a - sqrt(c)) * (a + sqrt(c)) ──
#
# Обычное правило разности квадратов требует, чтобы оба слагаемых были записаны как
# произведение чего-то на себя. Единица в выражении (x*x - 1) так не записана, поэтому
# сокращение (x*x - 1)/(x - 1) до x + 1 не находилось: Herbie отдавал ответ ценой в две
# условные единицы, мы тащили форму за восемнадцать. Проверка на полный квадрат живёт в
# коде, а не в шаблоне, потому что шаблоны у нас без предусловий.
def _square_split(sign):
    import math

    def build(eg, subst, eid):
        a = subst['?a']
        # Раскладывать имеет смысл только в числителе дроби: ради сокращения оно и
        # добавлялось. Без ограничения правило срабатывает повсюду, дистрибутивность
        # тут же собирает всё обратно, и граф уходит за двести тысяч узлов —
        # (x*x-1)/(x-1) считался шесть минут вместо мгновения.
        root = eg.uf.find(eid)
        in_numerator = any(
            node[0] == '/' and eg.uf.find(node[1]) == root
            for nodes in eg.classes.values() for node in nodes)
        if not in_numerator:
            return None

        num = None
        for node in eg.classes.get(eg.uf.find(subst['?c']), ()):
            if node[0] == 'num':
                num = node[1]
                break
        if num is None or num < 0:
            return None
        r = math.sqrt(num)
        if not math.isfinite(r) or r * r != num:      # только точный квадрат
            return None
        rn = eg.add_node(('num', r))
        lo = eg.add_node(('-', a, rn)) if sign > 0 else eg.add_node(('-', rn, a))
        hi = eg.add_node(('+', a, rn))
        return eg.add_node(('*', lo, hi))

    return build


RULES += [
    (('-', ('*', '?a', '?a'), '?c'), _square_split(+1)),
    (('-', '?c', ('*', '?a', '?a')), _square_split(-1)),
]


# ── Сокращение общего множителя в дроби — только там, где он доказуемо не ноль ──
#
# (a*b)/(a*c) = b/c верно лишь при a ≠ 0, иначе слева 0/0. Шаблоны предусловий не
# умеют, поэтому проверка живёт в коде и опирается на интервал класса: сокращаем,
# если интервал целиком лежит строго по одну сторону от нуля. Пустой домен у
# e-графа означает «проверить нечем» — правило тогда просто молчит.
#
# Цена вопроса видна на формуле корней квадратного уравнения: без сокращения
# множитель a остаётся и в числителе, и в знаменателе, форма стоит 45 единиц против
# 27 у Herbie при худшей границе. Ровно на этом месте он нас и обходил.
def _cancel_factor(where):
    def build(eg, subst, eid):
        a = subst['?a']
        if not eg.nonzero(a):
            return None
        if where == 'both':
            return eg.add_node(('/', subst['?b'], subst['?c']))
        if where == 'num':                      # (a*b)/a -> b
            return subst['?b']
        return eg.add_node(('/', ('num', 1.0), subst['?c']))   # a/(a*c) -> 1/c

    return build


# Держим отдельным списком, а не в общем наборе: на выражениях с корнями эти шесть
# правил удваивают e-граф (6056 узлов против 12121) и утраивают время извлечения,
# а нужны они ровно в одном месте — после подстановки ряда, где надо сократить
# общий множитель. Там графы маленькие, цена копеечная.
CANCEL_RULES = [
    (('/', ('*', '?a', '?b'), ('*', '?a', '?c')), _cancel_factor('both')),
    (('/', ('*', '?b', '?a'), ('*', '?a', '?c')), _cancel_factor('both')),
    (('/', ('*', '?a', '?b'), ('*', '?c', '?a')), _cancel_factor('both')),
    (('/', ('*', '?b', '?a'), ('*', '?c', '?a')), _cancel_factor('both')),
    (('/', ('*', '?a', '?b'), '?a'), _cancel_factor('num')),
    (('/', ('*', '?b', '?a'), '?a'), _cancel_factor('num')),
]

"""Правила переписывания. Все — тождества над вещественными числами.

Важно: это тождества для ТОЧНОЙ арифметики. В плавающей точке разные формы
дают разный результат — именно этим и занимается оптимизатор, выбирая
форму с меньшей границей ошибки или меньшей стоимостью.
Формат: (левая часть, правая часть, двустороннее?)
"""

RULES = [
    # коммутативность
    (('+', '?a', '?b'), ('+', '?b', '?a'), False),
    (('*', '?a', '?b'), ('*', '?b', '?a'), False),

    # ассоциативность
    (('+', ('+', '?a', '?b'), '?c'), ('+', '?a', ('+', '?b', '?c')), True),
    (('*', ('*', '?a', '?b'), '?c'), ('*', '?a', ('*', '?b', '?c')), True),

    # нейтральные элементы
    (('+', '?a', ('num', 0.0)), '?a', False),
    (('*', '?a', ('num', 1.0)), '?a', False),
    (('*', '?a', ('num', 0.0)), ('num', 0.0), False),

    # вычитание через отрицание — открывает ассоциативность для сумм
    (('-', '?a', '?b'), ('+', '?a', ('neg', '?b')), True),
    (('neg', ('neg', '?a')), '?a', False),
    (('-', '?a', '?a'), ('num', 0.0), False),
    (('+', '?a', ('neg', '?a')), ('num', 0.0), False),
    (('/', '?a', '?a'), ('num', 1.0), False),

    # дистрибутивность и факторизация (схема Горнера рождается здесь)
    (('+', ('*', '?a', '?c'), ('*', '?b', '?c')), ('*', ('+', '?a', '?b'), '?c'), True),
    (('+', ('*', '?c', '?a'), ('*', '?c', '?b')), ('*', '?c', ('+', '?a', '?b')), True),
    (('+', '?a', ('*', '?a', '?b')), ('*', '?a', ('+', ('num', 1.0), '?b')), True),

    # общий знаменатель: два деления превращаются в одно
    (('+', ('/', '?a', '?c'), ('/', '?b', '?c')), ('/', ('+', '?a', '?b'), '?c'), True),
    (('*', ('/', '?a', '?b'), '?c'), ('/', ('*', '?a', '?c'), '?b'), True),
    (('/', ('/', '?a', '?b'), '?c'), ('/', '?a', ('*', '?b', '?c')), True),

    # разность квадратов — убирает катастрофическое сокращение при a ≈ b
    (('-', ('*', '?a', '?a'), ('*', '?b', '?b')),
     ('*', ('-', '?a', '?b'), ('+', '?a', '?b')), True),

    # домножение на сопряжённое для корней:
    # sqrt(a) - sqrt(b) = (a - b) / (sqrt(a) + sqrt(b))
    (('-', ('sqrt', '?a'), ('sqrt', '?b')),
     ('/', ('-', '?a', '?b'), ('+', ('sqrt', '?a'), ('sqrt', '?b'))), True),

    # ⛔ Сопряжённое с одним корнем сюда НЕ добавлять без предусловий.
    #
    # Попытка 25.09.2026: a - sqrt(b) = (a*a - b) / (a + sqrt(b)) и симметричное ему.
    # Оба тождества верны только при ненулевом знаменателе, а e-граф предусловий не
    # знает. На sqrt(x) - sqrt(x) второе правило даёт (x - x) / (sqrt(x) - sqrt(x)),
    # то есть 0/0, дальше правило a/a = 1 превращает это в единицу — и класс, где
    # лежит 2*sqrt(x), схлопывается с классом единицы. После этого извлекается форма,
    # не равная исходному выражению: на sqrt(x) - sqrt(x) фронт выдал «x» с нулевой
    # границей при реальной ошибке 4.0. Ради 1.3 бита на формуле корней квадратного
    # уравнения ломать корректность нельзя — нужны условные правила, это отдельная
    # работа. Поймано адверсариальным блоком в run_tightness.py.

    # Разность кубов: x^3 - y^3 = (x - y)(x^2 + xy + y^2). Та же катастрофа, что и у
    # разности квадратов, но на степень глубже — без правила остаётся 16 бит ошибки.
    (('-', ('*', '?a', ('*', '?a', '?a')), ('*', '?b', ('*', '?b', '?b'))),
     ('*', ('-', '?a', '?b'),
      ('+', ('*', '?a', '?a'), ('+', ('*', '?a', '?b'), ('*', '?b', '?b')))), True),
    (('-', ('*', ('*', '?a', '?a'), '?a'), ('*', ('*', '?b', '?b'), '?b')),
     ('*', ('-', '?a', '?b'),
      ('+', ('*', '?a', '?a'), ('+', ('*', '?a', '?b'), ('*', '?b', '?b')))), True),

    # Квадрат суммы и разности: даёт свернуть (a+b)^2 - (a-b)^2 и обратно.
    (('*', ('+', '?a', '?b'), ('+', '?a', '?b')),
     ('+', ('*', '?a', '?a'), ('+', ('*', ('num', 2.0), ('*', '?a', '?b')), ('*', '?b', '?b'))), True),

    # корни и произведения
    (('*', ('sqrt', '?a'), ('sqrt', '?a')), '?a', False),
    (('sqrt', ('*', '?a', '?b')), ('*', ('sqrt', '?a'), ('sqrt', '?b')), True),

    # слияние умножения со сложением: fma(a,b,c) = a*b + c, но с ОДНИМ округлением
    # на всю операцию — промежуточное произведение не округляется. Это и есть то,
    # чем Herbie нас обыгрывал на схеме Горнера и на разности квадратов.
    (('+', ('*', '?a', '?b'), '?c'), ('fma', '?a', '?b', '?c'), True),
    (('-', ('*', '?a', '?b'), '?c'), ('fma', '?a', '?b', ('neg', '?c')), True),

    # экспонента и логарифм
    (('log', ('*', '?a', '?b')), ('+', ('log', '?a'), ('log', '?b')), True),
    (('exp', ('+', '?a', '?b')), ('*', ('exp', '?a'), ('exp', '?b')), True),
    (('log', ('/', '?a', '?b')), ('-', ('log', '?a'), ('log', '?b')), True),
]
